import PDFDocument from 'pdfkit'
import type { Cell, Column, ReportDoc } from './reports.service.js'

// Turns a report into a CSV file or a PDF. Both print exactly what the screen shows.

const peso = (n: number) => `${n < 0 ? '-' : ''}${Math.abs(n).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`
const int = (n: number) => n.toLocaleString('en-US', { maximumFractionDigits: 0 })

/** One cell as plain text. PDFs use the standard fonts, which have no peso sign, so amounts are plain numbers under a "PHP" heading. */
export function formatCell(value: Cell, kind: Column['kind']): string {
  if (value === null || value === undefined || value === '') return ''
  if (typeof value === 'string') return value
  if (kind === 'money') return peso(value)
  if (kind === 'pct') return `${value.toFixed(1)}%`
  if (kind === 'int') return int(value)
  return String(value)
}

const stamp = (iso: string) => {
  const d = new Date(iso), p = (n: number) => String(n).padStart(2, '0')
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())} ${p(d.getHours())}:${p(d.getMinutes())}`
}

const readingNumber = (doc: ReportDoc) => (doc.reading?.reading_no ? ` No. ${String(doc.reading.reading_no).padStart(6, '0')}` : '')

/** Spreadsheet programs run text that starts with = + - @ as a formula; a leading apostrophe stops that. */
function csvText(value: string): string {
  const safe = /^[=+\-@\t\r]/.test(value) ? `'${value}` : value
  return /[",\n\r]/.test(safe) ? `"${safe.replace(/"/g, '""')}"` : safe
}

export function toCsv(doc: ReportDoc): string {
  const lines: string[] = []
  const line = (cells: string[]) => lines.push(cells.map(csvText).join(','))
  line([doc.business.name || '9010 Grocery Store']); if (doc.business.tin) line([`TIN ${doc.business.tin}`]); if (doc.business.address) line([doc.business.address])
  line([`${doc.title}${readingNumber(doc)}`]); line([`Period: ${doc.period}`])
  for (const f of doc.filters) line([f])
  line([`Generated by ${doc.generated_by} on ${stamp(doc.generated_at)}`]); lines.push('')
  for (const s of doc.summary) line([s.label, s.kind === 'money' && typeof s.value === 'number' ? s.value.toFixed(2) : String(s.value ?? '')])
  for (const table of doc.tables) {
    lines.push('')
    if (table.title) line([table.title])
    line(table.columns.map((c) => c.label))
    const plain = (row: Cell[]) => row.map((v, i) => (v === null ? '' : typeof v === 'number' && table.columns[i]?.kind === 'money' ? v.toFixed(2) : String(v)))
    for (const row of table.rows) line(plain(row))
    if (table.totals) line(plain(table.totals))
  }
  // A byte-order mark so Excel opens it as UTF-8.
  return `﻿${lines.join('\r\n')}\r\n`
}

const INK = '#111827', MUTED = '#6b7280', RULE = '#d1d5db', SHADE = '#f3f4f6'

export function toPdf(doc: ReportDoc): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const widest = Math.max(0, ...doc.tables.map((t) => t.columns.length))
    const pdf = new PDFDocument({ size: 'A4', layout: widest > 7 ? 'landscape' : 'portrait', margins: { top: 40, bottom: 48, left: 36, right: 36 }, bufferPages: true, info: { Title: doc.title, Author: doc.business.name || '9010 Grocery Store' } })
    const chunks: Buffer[] = []
    pdf.on('data', (c: Buffer) => chunks.push(c))
    pdf.on('end', () => resolve(Buffer.concat(chunks)))
    pdf.on('error', reject)

    const left = pdf.page.margins.left, width = pdf.page.width - left - pdf.page.margins.right
    const bottom = () => pdf.page.height - pdf.page.margins.bottom

    // Letterhead
    pdf.font('Helvetica-Bold').fontSize(15).fillColor(INK).text(doc.business.name || '9010 Grocery Store', left, 40, { width })
    pdf.font('Helvetica').fontSize(9).fillColor(MUTED)
    if (doc.business.tin) pdf.text(`TIN ${doc.business.tin}`, { width })
    if (doc.business.address) pdf.text(doc.business.address, { width })
    pdf.moveDown(0.8)
    pdf.font('Helvetica-Bold').fontSize(13).fillColor(INK).text(`${doc.title}${readingNumber(doc)}`, { width })
    pdf.font('Helvetica').fontSize(9).fillColor(MUTED).text(`Period: ${doc.period}`, { width })
    for (const f of doc.filters) pdf.text(f, { width })
    pdf.text(`Generated by ${doc.generated_by} on ${stamp(doc.generated_at)}`, { width })
    pdf.moveDown(0.6)

    // Summary: label / value pairs in two columns
    if (doc.summary.length) {
      const colW = width / 2
      let y = pdf.y
      doc.summary.forEach((s, i) => {
        const x = left + (i % 2) * colW
        if (i % 2 === 0 && i > 0) y += 16
        if (y + 16 > bottom()) { pdf.addPage(); y = pdf.page.margins.top }
        pdf.font('Helvetica').fontSize(9).fillColor(MUTED).text(s.label, x, y, { width: colW * 0.58, lineBreak: false, ellipsis: true })
        const v = formatCell(s.value, s.kind)
        pdf.font('Helvetica-Bold').fontSize(9).fillColor(INK).text(s.kind === 'money' ? `PHP ${v}` : v, x + colW * 0.58, y, { width: colW * 0.38 - 8, align: 'right', lineBreak: false, ellipsis: true })
      })
      pdf.y = y + 22
    }

    for (const table of doc.tables) {
      const cols = table.columns
      // Column widths: numbers get a fixed share; text columns share the rest by the length of what they hold.
      const sample = (i: number) => Math.max(cols[i]!.label.length, ...table.rows.slice(0, 200).map((r) => formatCell(r[i] ?? null, cols[i]!.kind).length), table.totals ? formatCell(table.totals[i] ?? null, cols[i]!.kind).length : 0)
      const weights = cols.map((c, i) => (c.kind === 'text' ? Math.min(Math.max(sample(i), 5), 34) + 2.5 : Math.min(Math.max(sample(i), 6), 14) + 2.5))
      const total = weights.reduce((a, b) => a + b, 0)
      const widths = weights.map((w) => (w / total) * width)
      const pad = 4
      const rowH = (row: Cell[], bold = false) => {
        pdf.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(8)
        return Math.max(14, ...row.map((v, i) => pdf.heightOfString(formatCell(v ?? null, cols[i]!.kind), { width: widths[i]! - pad * 2 }) + 6))
      }
      const drawRow = (row: Cell[], y: number, opts: { head?: boolean; bold?: boolean; shade?: boolean } = {}) => {
        const h = opts.head ? 16 : rowH(row, opts.bold)
        if (opts.shade) pdf.rect(left, y, width, h).fill(SHADE)
        let x = left
        row.forEach((v, i) => {
          const c = cols[i]!
          pdf.font(opts.head || opts.bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(opts.head ? 7 : 8).fillColor(INK)
          const text = opts.head ? c.label.toUpperCase() : formatCell(v ?? null, c.kind)
          pdf.text(text, x + pad, y + 3.5, { width: widths[i]! - pad * 2, align: c.kind === 'text' ? 'left' : 'right', lineBreak: !opts.head, ellipsis: opts.head })
          x += widths[i]!
        })
        pdf.moveTo(left, y + h).lineTo(left + width, y + h).lineWidth(0.4).strokeColor(RULE).stroke()
        return h
      }
      if (pdf.y + 60 > bottom()) pdf.addPage()
      if (table.title) { pdf.font('Helvetica-Bold').fontSize(10).fillColor(INK).text(table.title, left, pdf.y, { width }); pdf.moveDown(0.3) }
      let y = pdf.y
      y += drawRow(cols.map(() => null), y, { head: true, shade: true })
      for (const row of table.rows) {
        if (y + rowH(row) > bottom()) { pdf.addPage(); y = pdf.page.margins.top; y += drawRow(cols.map(() => null), y, { head: true, shade: true }) }
        y += drawRow(row, y)
      }
      if (table.totals) {
        if (y + rowH(table.totals, true) > bottom()) { pdf.addPage(); y = pdf.page.margins.top }
        y += drawRow(table.totals, y, { bold: true, shade: true })
      }
      if (!table.rows.length) { pdf.font('Helvetica-Oblique').fontSize(8).fillColor(MUTED).text('No records for this period.', left + pad, y + 4, { width }); y += 18 }
      pdf.y = y + 14
    }

    // Footer on every page
    const range = pdf.bufferedPageRange()
    for (let i = 0; i < range.count; i++) {
      pdf.switchToPage(range.start + i)
      pdf.page.margins.bottom = 0 // writing in the bottom margin must not start a new page
      pdf.font('Helvetica').fontSize(8).fillColor(MUTED)
      pdf.text(`${doc.business.name || '9010 Grocery Store'} · ${doc.title} · ${doc.period}`, left, pdf.page.height - 34, { width: width - 60, lineBreak: false, ellipsis: true })
      pdf.text(`Page ${i + 1} of ${range.count}`, left + width - 60, pdf.page.height - 34, { width: 60, align: 'right', lineBreak: false })
    }
    pdf.end()
  })
}